'use client';

import React, { useState } from 'react';
import {
  Bot,
  CheckCircle2,
  XCircle,
  Clock,
  Sparkles,
  Info,
  ShieldCheck,
  Check,
  AlertTriangle,
} from 'lucide-react';
import { Recommendation, Session } from '../types';
import { updateRecommendationStatus } from '../lib/api';

interface AITeachingAssistantViewProps {
  session: Session | null;
  recommendations: Recommendation[];
  onRecommendationUpdated: (updated: Recommendation) => void;
  onToast: (type: 'success' | 'error' | 'info', title: string, desc?: string) => void;
}

export const AITeachingAssistantView: React.FC<AITeachingAssistantViewProps> = ({
  session,
  recommendations,
  onRecommendationUpdated,
  onToast,
}) => {
  const [filter, setFilter] = useState<'all' | 'pending' | 'accepted' | 'completed'>('all');
  const [updatingId, setUpdatingId] = useState<string | null>(null);

  const handleUpdate = async (rec: Recommendation, status: 'accepted' | 'dismissed' | 'completed') => {
    if (!session) return;
    try {
      setUpdatingId(rec.id);
      const updated = await updateRecommendationStatus(session.id, rec.id, status);
      onRecommendationUpdated(updated);
      onToast('success', 'Suggestion Updated', `Marked as ${status}.`);
    } catch (err: any) {
      onToast('error', 'Update Failed', err.message);
    } finally {
      setUpdatingId(null);
    }
  };

  const filtered = recommendations.filter((r) => {
    if (filter === 'all') return r.status !== 'dismissed';
    return r.status === filter;
  });

  return (
    <div className="space-y-6">
      {/* Top Banner */}
      <div className="flex flex-col md:flex-row md:items-center justify-between gap-4 p-5 rounded-2xl bg-white border border-slate-200 shadow-xs">
        <div>
          <div className="flex items-center gap-2">
            <div className="w-8 h-8 rounded-xl bg-emerald-50 text-emerald-700 flex items-center justify-center">
              <Bot className="w-4 h-4" />
            </div>
            <h2 className="text-xl font-bold text-slate-900">AI Teaching Assistant</h2>
            <span className="text-xs px-2.5 py-0.5 rounded-full bg-slate-100 text-slate-700 font-semibold border border-slate-200">
              Deterministic Rules Engine
            </span>
          </div>
          <p className="text-xs text-slate-500 mt-1">
            Explainable pedagogical recommendations derived offline from observed engagement and presence patterns.
          </p>
        </div>

        {/* Filter Buttons */}
        <div className="flex items-center gap-1.5 bg-slate-100 p-1 rounded-xl self-start md:self-auto text-xs">
          <button
            onClick={() => setFilter('all')}
            className={`px-3 py-1.5 rounded-lg font-semibold transition-all ${
              filter === 'all' ? 'bg-white text-slate-900 shadow-xs' : 'text-slate-600 hover:text-slate-900'
            }`}
          >
            Active ({recommendations.filter((r) => r.status !== 'dismissed').length})
          </button>
          <button
            onClick={() => setFilter('accepted')}
            className={`px-3 py-1.5 rounded-lg font-semibold transition-all ${
              filter === 'accepted' ? 'bg-white text-slate-900 shadow-xs' : 'text-slate-600 hover:text-slate-900'
            }`}
          >
            Accepted ({recommendations.filter((r) => r.status === 'accepted').length})
          </button>
          <button
            onClick={() => setFilter('completed')}
            className={`px-3 py-1.5 rounded-lg font-semibold transition-all ${
              filter === 'completed' ? 'bg-white text-slate-900 shadow-xs' : 'text-slate-600 hover:text-slate-900'
            }`}
          >
            Completed ({recommendations.filter((r) => r.status === 'completed').length})
          </button>
        </div>
      </div>

      {/* Ethics & Rule Engine Notice */}
      <div className="p-4 rounded-2xl bg-slate-50 border border-slate-200 text-xs text-slate-700 flex items-start gap-3">
        <ShieldCheck className="w-5 h-5 text-emerald-600 flex-shrink-0 mt-0.5" />
        <div className="space-y-1">
          <p className="font-semibold text-slate-900">Local Privacy-Preserving Rule Architecture</p>
          <p className="text-slate-600 leading-relaxed">
            Suggestions are generated by an explainable, deterministic statistical rule engine that analyzes participation drops,
            continuous instruction pacing, and audio dynamics. No student data or transcripts are ever sent to third-party cloud LLMs.
          </p>
        </div>
      </div>

      {/* Recommendations Cards List */}
      <div className="space-y-4">
        {filtered.length === 0 ? (
          <div className="p-8 text-center bg-white rounded-2xl border border-slate-200">
            <CheckCircle2 className="w-10 h-10 text-emerald-600 mx-auto mb-2" />
            <h4 className="text-sm font-bold text-slate-800">No Pending Suggestions</h4>
            <p className="text-xs text-slate-500 mt-0.5">
              Instruction pacing and participation dynamics remain stable according to current interval metrics.
            </p>
          </div>
        ) : (
          filtered.map((rec) => (
            <div
              key={rec.id}
              className={`p-5 rounded-2xl bg-white border transition-all shadow-xs ${
                rec.status === 'accepted'
                  ? 'border-emerald-200 ring-1 ring-emerald-500/10'
                  : rec.status === 'completed'
                  ? 'border-slate-200 opacity-80'
                  : 'border-slate-200'
              }`}
            >
              <div className="flex flex-col sm:flex-row sm:items-start justify-between gap-3">
                <div>
                  <div className="flex items-center gap-2">
                    <h3 className="text-sm font-bold text-slate-900">{rec.title}</h3>
                    <span
                      className={`text-[10px] font-bold uppercase px-2 py-0.5 rounded-full ${
                        rec.status === 'accepted'
                          ? 'bg-emerald-100 text-emerald-800'
                          : rec.status === 'completed'
                          ? 'bg-slate-100 text-slate-700'
                          : 'bg-amber-100 text-amber-800'
                      }`}
                    >
                      {rec.status}
                    </span>
                  </div>
                  <p className="text-xs text-slate-600 mt-1 leading-relaxed">{rec.explanation}</p>
                </div>

                <div className="flex-shrink-0 text-right">
                  <span className="text-[11px] font-semibold text-slate-500 bg-slate-50 px-2 py-1 rounded-lg border border-slate-200">
                    Confidence: {Math.round(rec.confidence * 100)}%
                  </span>
                </div>
              </div>

              {/* Supporting Evidence Breakdown */}
              {rec.evidence_json && (
                <div className="mt-3.5 p-3 rounded-xl bg-slate-50 border border-slate-200/80 text-xs space-y-1">
                  <div className="font-semibold text-slate-800 flex items-center gap-1.5">
                    <Info className="w-3.5 h-3.5 text-slate-500" />
                    <span>Supporting Sensor Evidence:</span>
                  </div>
                  <div className="grid grid-cols-2 sm:grid-cols-3 gap-2 text-[11px] text-slate-600 mt-1">
                    {rec.evidence_json.metric_name && (
                      <div>
                        <span className="text-slate-400">Metric:</span>{' '}
                        <span className="font-medium text-slate-700">{rec.evidence_json.metric_name}</span>
                      </div>
                    )}
                    {rec.evidence_json.interval && (
                      <div>
                        <span className="text-slate-400">Observed Interval:</span>{' '}
                        <span className="font-medium text-slate-700">{rec.evidence_json.interval}</span>
                      </div>
                    )}
                    {rec.evidence_json.recent_value !== undefined && (
                      <div>
                        <span className="text-slate-400">Observed Value:</span>{' '}
                        <span className="font-medium text-slate-700">{rec.evidence_json.recent_value}%</span>
                      </div>
                    )}
                  </div>
                  {rec.evidence_json.limitation && (
                    <p className="text-[10px] text-slate-500 italic mt-1">
                      Limitation: {rec.evidence_json.limitation}
                    </p>
                  )}
                </div>
              )}

              {/* Suggested Action & Buttons */}
              <div className="mt-4 pt-3 border-t border-slate-100 flex flex-col sm:flex-row sm:items-center justify-between gap-3">
                <div className="text-xs text-emerald-900 font-semibold flex items-center gap-1.5">
                  <Sparkles className="w-3.5 h-3.5 text-emerald-600 flex-shrink-0" />
                  <span>Suggested Action: {rec.suggested_action}</span>
                </div>

                <div className="flex items-center gap-2 self-end sm:self-auto">
                  {rec.status === 'pending' && (
                    <>
                      <button
                        onClick={() => handleUpdate(rec, 'accepted')}
                        disabled={updatingId === rec.id}
                        className="px-3 py-1.5 rounded-lg bg-emerald-600 hover:bg-emerald-700 text-white text-xs font-semibold shadow-xs transition-colors flex items-center gap-1"
                      >
                        <Check className="w-3 h-3" />
                        <span>Accept Suggestion</span>
                      </button>
                      <button
                        onClick={() => handleUpdate(rec, 'dismissed')}
                        disabled={updatingId === rec.id}
                        className="px-3 py-1.5 rounded-lg border border-slate-200 text-slate-600 hover:bg-slate-50 text-xs font-medium transition-colors"
                      >
                        Dismiss
                      </button>
                    </>
                  )}

                  {rec.status === 'accepted' && (
                    <button
                      onClick={() => handleUpdate(rec, 'completed')}
                      disabled={updatingId === rec.id}
                      className="px-3 py-1.5 rounded-lg bg-sky-600 hover:bg-sky-700 text-white text-xs font-semibold transition-colors flex items-center gap-1"
                    >
                      <CheckCircle2 className="w-3 h-3" />
                      <span>Mark Completed</span>
                    </button>
                  )}

                  {rec.status === 'completed' && (
                    <span className="text-xs font-semibold text-slate-500 flex items-center gap-1">
                      <CheckCircle2 className="w-3.5 h-3.5 text-emerald-600" />
                      <span>Completed in class</span>
                    </span>
                  )}
                </div>
              </div>
            </div>
          ))
        )}
      </div>
    </div>
  );
};
