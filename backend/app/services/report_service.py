import io
import csv
from datetime import datetime
from typing import Dict, Any, List
from fpdf import FPDF
from app.models.session import Session as ClassroomSession
from app.models.attendance import AttendanceRecord
from app.models.engagement import EngagementMetric
from app.models.recommendation import Recommendation

def generate_session_csv(
    session: ClassroomSession,
    attendance_records: List[AttendanceRecord],
    metrics: List[EngagementMetric],
    recommendations: List[Recommendation]
) -> str:
    """Generates an RFC-4180 compliant CSV export for a classroom session."""
    output = io.StringIO()
    writer = csv.writer(output)

    # 1. Session Metadata Header
    writer.writerow(["=== SESSION METADATA ==="])
    writer.writerow(["Session ID", session.id])
    writer.writerow(["Title", session.title])
    writer.writerow(["Course", session.course.name if session.course else "N/A"])
    writer.writerow(["Teacher", session.teacher_name])
    writer.writerow(["Status", session.status])
    writer.writerow(["Input Mode", session.input_mode])
    writer.writerow(["Start Time", session.start_time.isoformat() if session.start_time else "N/A"])
    writer.writerow(["End Time", session.end_time.isoformat() if session.end_time else "N/A"])
    writer.writerow([])

    # 2. Privacy & Data Limitations Notice
    writer.writerow(["=== PRIVACY & ETHICS STATEMENT ==="])
    writer.writerow([
        "Notice",
        "Behavioral activity indicators are non-invasive proxies and do not prove or disprove learning, attention, or comprehension. Never use for grading or punitive labeling."
    ])
    writer.writerow([])

    # 3. Attendance Register
    writer.writerow(["=== ATTENDANCE REGISTER ==="])
    writer.writerow([
        "Record ID",
        "Student Code",
        "Display Name",
        "Anonymous Track",
        "Status",
        "Observed Duration (s)",
        "Confidence",
        "Manually Corrected",
        "Notes"
    ])
    for rec in attendance_records:
        stu_code = rec.student.student_code if rec.student else "N/A"
        stu_name = rec.student.display_name if rec.student else "Anonymous Track"
        writer.writerow([
            rec.id,
            stu_code,
            stu_name,
            rec.anonymous_track_id or "N/A",
            rec.status,
            rec.observed_duration,
            rec.confidence,
            "Yes" if rec.manually_corrected else "No",
            rec.notes or ""
        ])
    writer.writerow([])

    # 4. Engagement Metrics Timeline
    writer.writerow(["=== ENGAGEMENT METRICS TIMELINE ==="])
    writer.writerow([
        "Interval Start (s)",
        "Interval End (s)",
        "Metric Name",
        "Value",
        "Modality",
        "Confidence"
    ])
    for m in metrics:
        writer.writerow([
            m.interval_start,
            m.interval_end,
            m.metric_name,
            m.metric_value,
            m.source_modality,
            m.confidence
        ])
    writer.writerow([])

    # 5. Teaching Recommendations
    writer.writerow(["=== AI TEACHING SUGGESTIONS ==="])
    writer.writerow(["Title", "Explanation", "Suggested Action", "Status", "Confidence"])
    for r in recommendations:
        writer.writerow([
            r.title,
            r.explanation,
            r.suggested_action,
            r.status,
            r.confidence
        ])

    return output.getvalue()

class PDFReport(FPDF):
    def header(self):
        self.set_font("Helvetica", "B", 14)
        self.cell(0, 8, "Multimodal Attendance & Engagement Agent", align="C", new_x="LMARGIN", new_y="NEXT")
        self.set_font("Helvetica", "", 10)
        self.set_text_color(100, 116, 139)
        self.cell(0, 6, "Classroom Intelligence & Engagement Summary Report", align="C", new_x="LMARGIN", new_y="NEXT")
        self.ln(4)

    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(148, 163, 184)
        self.cell(0, 10, f"Page {self.page_no()} | Generated by Multimodal Attendance Agent (Privacy-Preserving Offline)", align="C")

def generate_session_pdf(
    session: ClassroomSession,
    attendance_records: List[AttendanceRecord],
    metrics: List[EngagementMetric],
    recommendations: List[Recommendation]
) -> bytes:
    """Generates a professional PDF report for a classroom session."""
    pdf = PDFReport()
    pdf.set_auto_page_break(auto=True, margin=15)
    pdf.add_page()

    # Session Info Card
    pdf.set_fill_color(248, 250, 252)
    pdf.set_draw_color(226, 232, 240)
    pdf.rect(10, pdf.get_y(), 190, 36, style="FD")
    
    pdf.set_font("Helvetica", "B", 11)
    pdf.set_text_color(15, 23, 42)
    pdf.cell(95, 7, f"Session: {session.title[:45]}", border=0)
    pdf.cell(95, 7, f"Course: {session.course.name[:45] if session.course else 'N/A'}", border=0, new_x="LMARGIN", new_y="NEXT")
    
    pdf.set_font("Helvetica", "", 9)
    pdf.set_text_color(71, 85, 105)
    pdf.cell(95, 6, f"Teacher: {session.teacher_name}", border=0)
    pdf.cell(95, 6, f"Status: {session.status.upper()} | Mode: {session.input_mode}", border=0, new_x="LMARGIN", new_y="NEXT")
    
    start_str = session.start_time.strftime("%Y-%m-%d %H:%M UTC") if session.start_time else "N/A"
    pdf.cell(95, 6, f"Recorded Time: {start_str}", border=0)
    pdf.cell(95, 6, f"Total Registered: {len(attendance_records)} attendees", border=0, new_x="LMARGIN", new_y="NEXT")
    pdf.ln(12)

    # Privacy Notice Banner
    pdf.set_fill_color(240, 253, 244)
    pdf.set_draw_color(187, 247, 208)
    pdf.rect(10, pdf.get_y(), 190, 16, style="FD")
    pdf.set_font("Helvetica", "B", 8)
    pdf.set_text_color(22, 101, 52)
    pdf.cell(0, 5, "ETHICAL BOUNDARIES & DATA LIMITATIONS", border=0, new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 7.5)
    pdf.set_text_color(21, 128, 61)
    pdf.multi_cell(185, 4, "Observed indicators are non-invasive proxies for participation and presence dynamics. They never infer intelligence, emotion, or comprehension, and must never be used for automated disciplinary decisions.")
    pdf.ln(6)

    # Summary Stats
    present_cnt = sum(1 for r in attendance_records if r.status in ("present", "manually_confirmed"))
    late_cnt = sum(1 for r in attendance_records if r.status == "late")
    absent_cnt = sum(1 for r in attendance_records if r.status == "absent")
    rate = (present_cnt / len(attendance_records) * 100) if attendance_records else 0

    comp_metrics = [m.metric_value for m in metrics if m.metric_name == "composite_engagement"]
    avg_eng = sum(comp_metrics) / len(comp_metrics) if comp_metrics else 0.0

    pdf.set_font("Helvetica", "B", 10)
    pdf.set_text_color(15, 23, 42)
    pdf.cell(0, 6, f"Attendance Summary: {rate:.1f}% Verified ({present_cnt} Present, {late_cnt} Late, {absent_cnt} Absent) | Avg Indicator: {avg_eng:.1f}/100", border=0, new_x="LMARGIN", new_y="NEXT")
    pdf.ln(2)

    # Attendance Table
    pdf.set_fill_color(241, 245, 249)
    pdf.set_font("Helvetica", "B", 8)
    pdf.set_text_color(30, 41, 59)
    pdf.cell(30, 6, "Student Code", border=1, fill=True)
    pdf.cell(60, 6, "Student Name", border=1, fill=True)
    pdf.cell(30, 6, "Status", border=1, fill=True)
    pdf.cell(35, 6, "Observed Duration", border=1, fill=True)
    pdf.cell(35, 6, "Confidence", border=1, fill=True, new_x="LMARGIN", new_y="NEXT")

    pdf.set_font("Helvetica", "", 8)
    for rec in attendance_records[:25]:  # show up to 25 rows
        code = rec.student.student_code if rec.student else "ANON"
        name = rec.student.display_name if rec.student else (rec.anonymous_track_id or "Track")
        mins = int(rec.observed_duration // 60)
        secs = int(rec.observed_duration % 60)
        
        pdf.cell(30, 5, code, border=1)
        pdf.cell(60, 5, name[:30], border=1)
        pdf.cell(30, 5, rec.status.capitalize(), border=1)
        pdf.cell(35, 5, f"{mins}m {secs}s", border=1)
        pdf.cell(35, 5, f"{int(rec.confidence * 100)}%", border=1, new_x="LMARGIN", new_y="NEXT")

    pdf.ln(6)

    # Recommendations Section
    if recommendations:
        pdf.set_font("Helvetica", "B", 10)
        pdf.set_text_color(15, 23, 42)
        pdf.cell(0, 6, "AI Teaching Assistant - Explainable Suggestions:", border=0, new_x="LMARGIN", new_y="NEXT")
        pdf.ln(1)

        for rec in recommendations:
            pdf.set_font("Helvetica", "B", 8.5)
            pdf.set_text_color(30, 41, 59)
            pdf.cell(0, 5, f"* {rec.title} ({rec.status.upper()})", border=0, new_x="LMARGIN", new_y="NEXT")
            pdf.set_font("Helvetica", "", 8)
            pdf.set_text_color(71, 85, 105)
            pdf.multi_cell(185, 4, f"Explanation: {rec.explanation}")
            pdf.set_font("Helvetica", "I", 8)
            pdf.set_text_color(22, 101, 52)
            pdf.cell(0, 4, f"Action: {rec.suggested_action}", border=0, new_x="LMARGIN", new_y="NEXT")
            pdf.ln(2)

    return bytes(pdf.output())
